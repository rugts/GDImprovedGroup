        public static void CargarSiVacio(Sistema s)
        {
            string marca = Path.Combine(s.Carpeta, "carta_good_moov_v1.txt");
            if (File.Exists(marca)) return;
            if (s.TotalPlatos > 0 || s.TotalInsumos > 0 || s.TotalPedidos > 0 || s.TotalBoletas > 0) return;
            if (InsumoNombre.Length > s.Insumos.Length || PlatoNombre.Length > s.Platos.Length)
                throw new InvalidOperationException("La carta inicial supera la capacidad del sistema.");
            for (int i = 0; i < Receta.GetLength(0); i++)
            {
                if (Receta[i, 0] < 1 || Receta[i, 0] > PlatoNombre.Length ||
                    Receta[i, 1] < 1 || Receta[i, 1] > InsumoNombre.Length)
                    throw new InvalidOperationException("La carta inicial contiene una receta con identificadores incorrectos.");
            }

            for (int i = 0; i < InsumoNombre.Length; i++)
                s.Insumos[s.TotalInsumos++] = new Insumo { Id = i + 1, Nombre = InsumoNombre[i], Stock = InsumoStock[i], Alerta = InsumoAlerta[i] };
            for (int i = 0; i < PlatoNombre.Length; i++)
                s.Platos[s.TotalPlatos++] = new Plato { Id = i + 1, Nombre = PlatoNombre[i], Categoria = PlatoCategoria[i], Precio = PlatoPrecio[i] };
            for (int i = 0; i < Receta.GetLength(0); i++)
                s.Recetas[Receta[i, 0], Receta[i, 1]] = Receta[i, 2];

            s.GuardarTodo();
            File.WriteAllText(marca, "carta cargada");
        }
